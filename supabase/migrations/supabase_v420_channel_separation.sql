create or replace function public.nexus_v420_ads_click_enqueue()
returns trigger
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  c_bot constant text := '(bot|crawl|spider|slurp|headless|preview|scan|curl|wget|python|java/|okhttp|monitor|lighthouse|pagespeed|telegrambot|facebookexternalhit)';
begin
  perform set_config('statement_timeout','2000',true);
  perform set_config('lock_timeout','1000',true);
  begin
    -- Fail-closed: só entra quem traz sinais positivos do clique comprovado.
    if lower(coalesce(new.device_type,'')) not in ('mobile','desktop','tablet')
       or btrim(coalesce(new.user_agent,'')) = ''
       or coalesce(new.user_agent,'') ~* c_bot
       or lower(coalesce(new.metadata->>'is_bot','false')) in ('true','1','yes')
       or lower(coalesce(new.metadata->>'proved_human','false')) not in ('true','1','yes')
       or coalesce(new.metadata->>'proof','') <> 'interstitial_beacon' then
      return new;
    end if;
    perform public.nexus_v420_enqueue(
      'public.ads_clicks', new.id::text, 'grupo_cliques',
      jsonb_build_object(
        'source','public.ads_clicks','click_id',new.id::text,
        'site',new.site_slug,'slot',new.slot,'advertiser',new.advertiser,
        'network',new.network,'country',new.country,'device',new.device_type,
        'created_at',new.created_at,'metadata',new.metadata
      )
    );
  exception when others then
    perform public.nexus_v420_sintonizado('v420-click-trigger','grupo_cliques',
      sqlstate || ': ' || left(sqlerrm,300));
  end;
  return new;
end;
$function$;

