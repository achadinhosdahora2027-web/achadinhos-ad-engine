-- -----------------------------------------------------------------------------
-- 10. C2 diário passa a materializar fatos na tabela C2; não envia diretamente.
-- Só usa preço BRL positivo, link HTTPS e atualização <=7 dias.
-- -----------------------------------------------------------------------------
create or replace function public.nexus_telegram_ofertas_broadcast()
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'extensions', 'pg_temp'
as $function$
declare
  r record;
  v_n integer:=0;
  v_dest64 text;
  v_action text;
  v_key text;
begin
  perform set_config('statement_timeout','2000',true);
  perform set_config('lock_timeout','1000',true);
  begin
    for r in
      select id,titulo,preco_atual,preco_de,desconto_pct,loja_origem,link_afiliado,meta_dados
        from public.produtos_ofertas
       where ativo is true and upper(coalesce(moeda,''))='BRL'
         and preco_atual>0 and link_afiliado~*'^https://[^[:space:]]+$'
         and atualizado_em>=now()-interval '7 days'
       order by atualizado_em desc,desconto_pct desc nulls last
       limit 4
    loop
      v_key:='catalog:'||r.id||':'||to_char(current_date,'YYYYMMDD');
      v_dest64:=replace(translate(replace(encode(convert_to(r.link_afiliado,'UTF8'),'base64'),E'\n',''),'+/','-_'),'=','');
      v_action:='https://www.aquitemachadinhos.com.br/go?marca=auto&dest64='||v_dest64||
                '&sid=tg_ofertas_v420_'||left(regexp_replace(r.id,'[^a-zA-Z0-9]','','g'),28);
      insert into public.nexus_telegram_c2_ofertas
        (source_key,offer_id,titulo,loja,preco_brl,preco_de_brl,click_url,action_url,button_text,metadata)
      values
        (v_key,r.id,left(r.titulo,180),left(r.loja_origem,100),r.preco_atual,r.preco_de,
         r.link_afiliado,v_action,'Ver oferta',coalesce(r.meta_dados,'{}'::jsonb))
      on conflict(source_key) do nothing;
      if found then v_n:=v_n+1; end if;
    end loop;
    return case when v_n=0
      then jsonb_build_object('ok',true,'silencio',true,'motivo','nenhuma oferta BRL fresca e inédita')
      else jsonb_build_object('ok',true,'enfileiradas',v_n,'destino','-1004317377063') end;
  exception when others then
    perform public.nexus_v420_sintonizado('v420-c2-materialize','ofertas',
      sqlstate||': '||left(sqlerrm,260));
    return jsonb_build_object('ok',false,'motivo','Sintonizado em Análise');
  end;
end;
$function$;

