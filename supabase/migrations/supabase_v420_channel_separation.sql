-- Asserts finais: qualquer divergência cancela TODA a migração.
do $verify$
declare
  v_before record;
  v_after record;
  v_routes integer;
begin
  select * into v_before from nexus_v420_catalog_guard;
  select count(*)::bigint total,count(*) filter(where active is true)::bigint ativos
    into v_after from public.ads;
  if v_before.total<>v_after.total or v_before.ativos<>v_after.ativos then
    raise exception 'v420 abortada: catálogo mudou (%/% -> %/%)',
      v_before.total,v_before.ativos,v_after.total,v_after.ativos;
  end if;
  select count(*) into v_routes from public.nexus_v420_channel_routes where enabled;
  if v_routes<>4
     or (select count(distinct source_relation) from public.nexus_v420_channel_routes where enabled)<>4
     or (select count(distinct channel_key) from public.nexus_v420_channel_routes where enabled)<>4
     or (select count(distinct chat_id) from public.nexus_v420_channel_routes where enabled)<>4 then
    raise exception 'v420 abortada: mapa não é 1:1 (rotas=%)',v_routes;
  end if;
  if exists(select 1 from public.nexus_v420_channel_routes where to_regclass(source_relation) is null) then
    raise exception 'v420 abortada: fonte registrada não existe';
  end if;
  if (select count(*) from public.nexus_v360_node_endpoints where ativo)<>13
     or (select count(distinct project_ref) from public.nexus_v360_node_endpoints where ativo)<>13 then
    raise exception 'v420 abortada: frota analítica não contém 13 satélites 1:1';
  end if;
end;
$verify$;

