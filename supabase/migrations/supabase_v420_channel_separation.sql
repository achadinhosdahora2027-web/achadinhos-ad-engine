create or replace function public.nexus_v420_conversion_enqueue()
returns trigger
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_status text;
  v_amount numeric;
begin
  perform set_config('statement_timeout','2000',true);
  perform set_config('lock_timeout','1000',true);
  begin
    v_status := lower(btrim(coalesce(nullif(new.raw->>'transaction_status',''),new.status,'')));
    v_amount := coalesce(new.commission_amount,0);
    -- Silêncio absoluto para delta zero, pendência, reversão ou status desconhecido.
    if v_amount <= 0 or v_status not in
       ('approved','confirmed','validated','locked','paid','completed') then
      return new;
