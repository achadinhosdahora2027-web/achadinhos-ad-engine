-- -----------------------------------------------------------------------------
-- 6. Entrada RPC de ofertas. Recebe apenas preço BRL positivo + link HTTPS.
-- O action_url usa o shortener Cloudflare; dest64 preserva o fallback específico.
-- -----------------------------------------------------------------------------
create or replace function public.nexus_v420_offer_enqueue(p_offer jsonb)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_id bigint;
  v_price numeric;
  v_old numeric;
  v_click text;
  v_action text;
  v_key text;
  v_dest64 text;
  v_brand text;
begin
  perform set_config('statement_timeout','2000',true);
  perform set_config('lock_timeout','1000',true);
  begin
    if p_offer is null or jsonb_typeof(p_offer) <> 'object' then
      return jsonb_build_object('ok',false,'motivo','payload_invalido');
    end if;
    if btrim(coalesce(p_offer->>'title','')) = '' then
      return jsonb_build_object('ok',false,'motivo','titulo_invalido');
    end if;
    v_price := replace(coalesce(p_offer->>'price_brl',''),',','.')::numeric;
    if v_price <= 0 then
      return jsonb_build_object('ok',false,'motivo','preco_brl_invalido');
    end if;
    begin
      v_old := nullif(replace(coalesce(p_offer->>'original_price_brl',''),',','.'),'')::numeric;
    exception when others then v_old := null;
    end;
    if v_old is not null and v_old <= v_price then v_old := null; end if;
    v_click := btrim(coalesce(p_offer->>'click_url',''));
    if v_click !~* '^https://[^[:space:]]+$' then
      return jsonb_build_object('ok',false,'motivo','click_url_invalido');
    end if;
    v_key := left(coalesce(nullif(btrim(p_offer->>'source_key'),''),
                    md5(v_click || '|' || coalesce(p_offer->>'title',''))),200);
    v_brand := left(lower(regexp_replace(coalesce(p_offer->>'brand','auto'),'[^a-z0-9_]','','g')),40);
    if v_brand = '' then v_brand := 'auto'; end if;
    v_dest64 := replace(translate(replace(encode(convert_to(v_click,'UTF8'),'base64'),E'\n',''),'+/','-_'),'=','');
    v_action := 'https://www.aquitemachadinhos.com.br/go?marca=' || v_brand ||
                '&dest64=' || v_dest64 || '&sid=tg_ofertas_v420_' ||
                left(regexp_replace(v_key,'[^a-zA-Z0-9]','','g'),32);

    insert into public.nexus_telegram_c2_ofertas
      (source_key,offer_id,titulo,loja,preco_brl,preco_de_brl,cupom,
       click_url,action_url,button_text,metadata)
    values
      (v_key,left(p_offer->>'offer_id',120),left(btrim(p_offer->>'title'),180),
       left(p_offer->>'merchant',100),v_price,v_old,left(p_offer->>'coupon',80),
       v_click,v_action,left(coalesce(nullif(p_offer->>'button_text',''),'Ver oferta'),48),
       coalesce(p_offer->'metadata','{}'::jsonb))
    on conflict (source_key) do nothing
    returning id into v_id;

    if v_id is null then
      return jsonb_build_object('ok',true,'queued',false,'motivo','duplicado_contido');
    end if;
    return jsonb_build_object('ok',true,'queued',true,'id',v_id);
  exception when others then
    perform public.nexus_v420_sintonizado('v420-offer-rpc','ofertas',
      sqlstate || ': ' || left(sqlerrm,300));
    return jsonb_build_object('ok',false,'motivo','Sintonizado em Análise');
  end;
end;
$function$;
