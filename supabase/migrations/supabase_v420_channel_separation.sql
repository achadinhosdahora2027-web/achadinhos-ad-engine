-- -----------------------------------------------------------------------------
-- 8. Reconciliador assíncrono pg_net. Falha é terminal e não gera reenvio.
-- -----------------------------------------------------------------------------
create or replace function public.nexus_v420_reconcile(p_limit integer default 40)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'net', 'pg_temp'
as $function$
declare
  r record;
  v_res jsonb;
  v_http integer;
  v_ok boolean;
  v_body text;
  v_done integer := 0;
  v_fail integer := 0;
begin
  perform set_config('statement_timeout','2000',true);
  perform set_config('lock_timeout','1000',true);
  begin
    for r in
      select id,request_id,channel_key from public.nexus_v420_dispatch_log
       where reconciled_at is null order by id limit greatest(1,least(coalesce(p_limit,40),100))
       for update skip locked
    loop
      begin
        v_res := null;
        select to_jsonb(x) into v_res from net._http_response x where x.id=r.request_id;
        if v_res is null then continue; end if;
        v_http := coalesce((v_res->>'status_code')::integer,0);
        v_body := coalesce(v_res->>'content','');
        begin
          v_ok := v_http=200 and coalesce((v_body::jsonb->>'ok')::boolean,false);
        exception when others then v_ok := false;
        end;
        update public.nexus_v420_dispatch_log
           set reconciled_at=now(),http_status=v_http,telegram_ok=v_ok,
               response_preview=left(v_body,300)
         where id=r.id;
        update public.nexus_v420_event_registry
           set state=case when v_ok then 'delivered' else 'failed' end,
               finalized_at=now()
         where request_id=r.request_id;
        delete from net._http_response where id=r.request_id;
        v_done := v_done+1;
        if not v_ok then
          v_fail := v_fail+1;
          perform public.nexus_v420_sintonizado('v420-telegram-network',r.channel_key,
            'Sintonizado em Análise · request_id='||r.request_id||' · HTTP '||v_http);
        end if;
      exception when others then
        perform public.nexus_v420_sintonizado('v420-reconcile',r.channel_key,
          sqlstate || ': ' || left(sqlerrm,260));
      end;
    end loop;
    return jsonb_build_object('reconciliados',v_done,'falhas',v_fail);
  exception when others then
    perform public.nexus_v420_sintonizado('v420-reconcile',null,
      sqlstate || ': ' || left(sqlerrm,260));
    return jsonb_build_object('sintonizado',true,'motivo','Sintonizado em Análise');
  end;
end;
$function$;

-- -----------------------------------------------------------------------------
-- 9. Flush mestre: uma mensagem consolidada por canal/ciclo.
-- Submissão ao pg_net, recibo e DELETE da fila são uma única subtransação.
-- -----------------------------------------------------------------------------
create or replace function public.nexus_v420_flush_10s(p_block integer default 40)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'extensions', 'net', 'pg_temp'
as $function$
declare
  r_route record;
  v_token text;
  v_enabled text;
  v_ids bigint[];
  v_registry_ids bigint[];
  v_pks text[];
  v_rows jsonb;
  v_n integer;
  v_limit integer;
  v_text text;
  v_body jsonb;
  v_req bigint;
  v_deleted integer;
  v_results jsonb := '[]'::jsonb;
begin
  perform set_config('statement_timeout','2000',true);
  perform set_config('lock_timeout','1000',true);
  begin
    if not pg_try_advisory_xact_lock(hashtext('nexus-v420-flush')) then
      return jsonb_build_object('idle',true,'motivo','outro flush possui o lock');
    end if;
    perform public.nexus_v420_reconcile(40);
    select value into v_enabled from public.nexus_growth_secrets where key='telegram_alerts_enabled';
    if coalesce(v_enabled,'false') <> 'true' then
      return jsonb_build_object('idle',true,'motivo','kill-switch telegram_alerts_enabled=false');
    end if;
    select value into v_token from public.nexus_growth_secrets where key='telegram_bot_token';
    if coalesce(btrim(v_token),'') = '' then
      perform public.nexus_v420_sintonizado('v420-flush',null,'telegram_bot_token ausente');
      return jsonb_build_object('sintonizado',true,'motivo','Sintonizado em Análise');
    end if;

    for r_route in
      select * from public.nexus_v420_channel_routes where enabled order by channel_key
    loop
      begin
        v_limit := case r_route.channel_key when 'atendimento' then 6 when 'ofertas' then 8
                     when 'vendas_real' then 12 else least(greatest(coalesce(p_block,40),1),40) end;
        select array_agg(id order by id),array_agg(registry_id order by id),
               array_agg(source_pk order by id),jsonb_agg(payload order by id)
          into v_ids,v_registry_ids,v_pks,v_rows
          from (
            select id,registry_id,source_pk,payload
              from public.nexus_v420_channel_outbox
             where channel_key=r_route.channel_key
               and source_relation=r_route.source_relation
             order by id limit v_limit
             for update skip locked
          ) q;
        v_n := coalesce(array_length(v_ids,1),0);
        if v_n=0 then continue; end if;

        v_text := case r_route.layout_key
          when 'clicks_ledger' then public.nexus_v420_layout_clicks(v_rows)
          when 'sentinel_capture' then public.nexus_v420_layout_capture(v_rows)
          when 'cash_close' then public.nexus_v420_layout_sales(v_rows)
          when 'offer_buttons' then public.nexus_v420_layout_offers(v_rows)
          else null end;

        if v_text is null or btrim(v_text)='' then
          update public.nexus_v420_event_registry
             set state='dropped',finalized_at=now()
           where registry_id=any(v_registry_ids);
          delete from public.nexus_v420_channel_outbox where id=any(v_ids);
          v_results := v_results || jsonb_build_array(jsonb_build_object(
            'canal',r_route.channel_key,'eventos',v_n,'enviado',false,'motivo','delta_zero_ou_layout_fechado'));
          continue;
        end if;

        v_body := jsonb_build_object(
          'chat_id',r_route.chat_id,'text',left(v_text,4000),
          'parse_mode','HTML','link_preview_options',jsonb_build_object('is_disabled',true)
        );
        if r_route.layout_key='offer_buttons' then
          v_body := v_body || jsonb_build_object('reply_markup',public.nexus_v420_offer_buttons(v_rows));
        end if;

        select net.http_post(
          url:='https://api.telegram.org/bot'||v_token||'/sendMessage',
          headers:='{"Content-Type":"application/json"}'::jsonb,
          body:=v_body,
          timeout_milliseconds:=1000
        ) into v_req;
        if v_req is null then raise exception 'pg_net não devolveu request_id'; end if;

        insert into public.nexus_v420_dispatch_log
          (request_id,channel_key,chat_id,source_relation,source_pks,event_count,body_sha256)
        values
          (v_req,r_route.channel_key,r_route.chat_id,r_route.source_relation,v_pks,v_n,
           encode(extensions.digest(v_text,'sha256'),'hex'));

        update public.nexus_v420_event_registry
           set state='submitted',request_id=v_req,submitted_at=now()
         where registry_id=any(v_registry_ids);

        -- Limpeza imediatamente depois da submissão. Se qualquer comando acima/abaixo
        -- falhar, o bloco EXCEPTION desfaz também a solicitação pg_net.
        delete from public.nexus_v420_channel_outbox where id=any(v_ids);
        get diagnostics v_deleted=row_count;
        if v_deleted<>v_n then raise exception 'flush parcial: esperado %, apagado %',v_n,v_deleted; end if;

        v_results := v_results || jsonb_build_array(jsonb_build_object(
          'canal',r_route.channel_key,'chat_id',r_route.chat_id,'eventos',v_n,
          'enviado',true,'request_id',v_req,'fila_limpa',v_deleted));
      exception when others then
        perform public.nexus_v420_sintonizado('v420-flush',r_route.channel_key,
          sqlstate || ': ' || left(sqlerrm,260));
        v_results := v_results || jsonb_build_array(jsonb_build_object(
          'canal',r_route.channel_key,'enviado',false,'motivo','Sintonizado em Análise'));
      end;
    end loop;
    return jsonb_build_object('versao','v420.0','resultados',v_results,'aferido_em',now());
  exception when others then
    perform public.nexus_v420_sintonizado('v420-flush',null,
      sqlstate || ': ' || left(sqlerrm,260));
    return jsonb_build_object('sintonizado',true,'motivo','Sintonizado em Análise');
  end;
end;
$function$;

