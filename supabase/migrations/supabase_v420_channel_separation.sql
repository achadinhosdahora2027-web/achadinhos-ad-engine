create or replace view public.nexus_v420_channel_map_v as
select r.source_relation,
       to_regclass(r.source_relation) is not null as source_exists,
       r.channel_key,r.chat_id,r.channel_title,r.layout_key,r.enabled,r.verified_at,
       coalesce(q.queued,0) as queued,
       d.last_submitted_at,d.last_telegram_ok
from public.nexus_v420_channel_routes r
left join (
  select source_relation,channel_key,count(*) queued
  from public.nexus_v420_channel_outbox group by 1,2
) q using(source_relation,channel_key)
left join lateral (
  select submitted_at last_submitted_at,telegram_ok last_telegram_ok
  from public.nexus_v420_dispatch_log l
  where l.source_relation=r.source_relation and l.channel_key=r.channel_key
  order by id desc limit 1
) d on true
order by r.channel_key;

