-- Frota analítica: os 13 PostgRESTs recebem submissões pg_net assíncronas. Cada
-- nó é isolado por EXCEPTION, com os mesmos limites do Job 60; resposta instável
-- é reconciliada e removida de net._http_response para liberar recursos.
create or replace function public.nexus_v365_fleet_dispatch(
  p_evento jsonb,
  p_max_minuto integer default 3,
  p_max_hora integer default 40
) returns jsonb
language plpgsql
security definer
set search_path to 'public', 'extensions', 'net', 'pg_temp'
as $function$
declare
  r record;
  v_hmac text;
  v_corpo text;
  v_req bigint;
  v_porteiro jsonb;
  v_n integer := 0;
  v_contido integer := 0;
  v_falhas integer := 0;
  v_kms text;
  v_cred text;
begin
  perform set_config('statement_timeout','2000',true);
  perform set_config('lock_timeout','1000',true);
  begin
    if p_evento is null or jsonb_typeof(p_evento)<>'object'
       or btrim(coalesce(p_evento->>'keyword',''))=''
       or btrim(coalesce(p_evento->>'link',p_evento->>'source_url',''))='' then
      return jsonb_build_object('ok',false,'motivo','evento_analitico_incompleto');
    end if;
    select value into v_kms from public.nexus_growth_secrets where key='nexus_satellites_kms';
    if coalesce(btrim(v_kms),'')='' then
      perform public.nexus_v420_sintonizado('v420-fleet','13-satellites','KMS ausente');
      return jsonb_build_object('sintonizado',true,'motivo','Sintonizado em Análise');
    end if;
    v_corpo:=p_evento::text;

    for r in
      select node,url,secret_enc,project_ref
      from public.nexus_v360_node_endpoints
      where ativo and secret_enc is not null
      order by node
    loop
      begin
        v_porteiro:=public.nexus_v360_tg_gate(
          'node:'||r.node,'disp:'||to_char(now(),'YYYY-MM-DD HH24:MI'),
          1,greatest(1,least(coalesce(p_max_minuto,3),10)),
          greatest(1,least(coalesce(p_max_hora,40),100)));
        if not coalesce((v_porteiro->>'pode')::boolean,false) then
          v_contido:=v_contido+1;
          insert into public.nexus_v365_fleet_dispatch_log(node,evento,veredito)
          values(r.node,coalesce(p_evento->>'tipo','stream'),
                 'contido: '||coalesce(v_porteiro->>'motivo','limite'));
          continue;
        end if;

        v_cred:=extensions.pgp_sym_decrypt(decode(r.secret_enc,'hex'),v_kms);
        if coalesce(btrim(v_cred),'')='' then raise exception 'credencial decifrada vazia'; end if;
        v_hmac:=public.nexus_v360_webhook_sign(v_corpo,v_kms);
        select net.http_post(
          url:=r.url,
          headers:=jsonb_build_object(
            'apikey',v_cred,'Authorization','Bearer '||v_cred,
            'Content-Type','application/json','Prefer','return=minimal',
            'X-Nexus-Event',coalesce(p_evento->>'tipo','stream_match'),
            'X-Nexus-Node',r.node,
            'X-Nexus-Signature-256','sha256='||v_hmac),
          body:=jsonb_build_object(
            'source_url',coalesce(p_evento->>'link',p_evento->>'source_url'),
            'target_keyword',p_evento->>'keyword',
            'platform',coalesce(p_evento->>'platform','bluesky'),
            'author_handle',coalesce(p_evento->>'casa',p_evento->>'author_handle','nexus'),
            'mention_text',left(coalesce(p_evento->>'produto',p_evento->>'texto',''),900),
            'language',coalesce(p_evento->>'language',case when upper(coalesce(p_evento->>'country','BR'))='BR' then 'pt' else 'en' end)),
          timeout_milliseconds:=1000
        ) into v_req;
        if v_req is null then raise exception 'pg_net sem request_id'; end if;
        insert into public.nexus_v365_fleet_dispatch_log(node,evento,request_id,veredito)
        values(r.node,coalesce(p_evento->>'tipo','stream'),v_req,'despachado v420');
        v_n:=v_n+1;
      exception when others then
        v_falhas:=v_falhas+1;
        perform public.nexus_v420_sintonizado('v420-fleet',r.node,
          'Sintonizado em Análise · '||sqlstate||': '||left(sqlerrm,200));
        insert into public.nexus_v365_fleet_dispatch_log(node,evento,veredito)
        values(r.node,coalesce(p_evento->>'tipo','stream'),
               'Sintonizado em Análise: '||left(sqlerrm,120));
      end;
    end loop;
    return jsonb_build_object('despachados',v_n,'contidos',v_contido,'falhas',v_falhas,
      'nos_ativos',(select count(*) from public.nexus_v360_node_endpoints where ativo));
  exception when others then
    perform public.nexus_v420_sintonizado('v420-fleet','13-satellites',
      'Sintonizado em Análise · '||sqlstate||': '||left(sqlerrm,220));
    return jsonb_build_object('sintonizado',true,'motivo','Sintonizado em Análise');
  end;
end;
$function$;

create or replace function public.nexus_v365_fleet_consume()
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'net', 'pg_temp'
as $function$
declare
  r record;
  v_res jsonb;
  v_http integer;
  v_ok integer:=0;
  v_err integer:=0;
  v_pend integer:=0;
begin
  perform set_config('statement_timeout','2000',true);
  perform set_config('lock_timeout','1000',true);
  begin
    for r in
      select id,node,request_id from public.nexus_v365_fleet_dispatch_log
      where request_id is not null and http is null order by id limit 60
      for update skip locked
    loop
      begin
        v_res:=null;
        select to_jsonb(x) into v_res from net._http_response x where x.id=r.request_id;
        if v_res is null then v_pend:=v_pend+1; continue; end if;
        v_http:=coalesce((v_res->>'status_code')::integer,0);
        update public.nexus_v365_fleet_dispatch_log
        set http=v_http,
            veredito=case when v_http in(200,201) then 'espelhado (http '||v_http||')'
                          else 'Sintonizado em Análise · HTTP '||v_http end
        where id=r.id;
        delete from net._http_response where id=r.request_id;
        if v_http in(200,201) then v_ok:=v_ok+1;
        else
          v_err:=v_err+1;
          perform public.nexus_v420_sintonizado('v420-fleet-network',r.node,
            'Sintonizado em Análise · HTTP '||v_http);
        end if;
      exception when others then
        v_err:=v_err+1;
        perform public.nexus_v420_sintonizado('v420-fleet-consume',r.node,
          'Sintonizado em Análise · '||sqlstate||': '||left(sqlerrm,200));
        update public.nexus_v365_fleet_dispatch_log
          set veredito='Sintonizado em Análise: '||left(sqlerrm,100) where id=r.id;
      end;
    end loop;
    return jsonb_build_object('espelhados',v_ok,'falhas',v_err,'pendentes',v_pend);
  exception when others then
    perform public.nexus_v420_sintonizado('v420-fleet-consume','13-satellites',
      'Sintonizado em Análise · '||sqlstate||': '||left(sqlerrm,200));
    return jsonb_build_object('sintonizado',true,'motivo','Sintonizado em Análise');
  end;
end;
$function$;

revoke all on function public.nexus_v365_fleet_dispatch(jsonb,integer,integer),
                       public.nexus_v365_fleet_consume()
  from public,anon,authenticated,service_role;
grant execute on function public.nexus_v365_fleet_dispatch(jsonb,integer,integer) to service_role;

create or replace function public.nexus_v420_enqueue(
  p_source_relation text,
  p_source_pk text,
  p_channel_key text,
  p_payload jsonb
) returns bigint
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_registry bigint;
  v_outbox bigint;
  v_inserted integer;
begin
  perform set_config('statement_timeout','2000',true);
  perform set_config('lock_timeout','1000',true);
  begin
    if p_source_pk is null or btrim(p_source_pk) = '' or p_payload is null then
      return null;
    end if;
    if not exists (
      select 1 from public.nexus_v420_channel_routes
       where source_relation = p_source_relation
         and channel_key = p_channel_key
         and enabled
    ) then
      perform public.nexus_v420_sintonizado('v420-enqueue',p_source_relation,
        'rota 1:1 inexistente ou desativada; evento recusado');
      return null;
    end if;

    insert into public.nexus_v420_event_registry(source_relation,source_pk,channel_key)
    values (p_source_relation,left(p_source_pk,240),p_channel_key)
    on conflict (source_relation,source_pk) do nothing
    returning registry_id into v_registry;
    get diagnostics v_inserted = row_count;
    if v_inserted = 0 then
      return null; -- já enfileirado/submetido: contenção definitiva de duplicidade
    end if;

    insert into public.nexus_v420_channel_outbox
      (registry_id,source_relation,source_pk,channel_key,payload)
    values
      (v_registry,p_source_relation,left(p_source_pk,240),p_channel_key,p_payload)
    returning id into v_outbox;
    return v_outbox;
  exception when others then
    perform public.nexus_v420_sintonizado('v420-enqueue',p_source_relation,
      sqlstate || ': ' || left(sqlerrm,320));
    return null;
  end;
end;
$function$;

