CREATE OR REPLACE FUNCTION public.nexus_galaxy_wave_sweep(p_max_hosts integer DEFAULT 20, p_shard text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'net'
AS $function$
declare
  v_rec record; v_url text; v_req bigint; v_dispatched int := 0; v_log text;
begin
  perform set_config('statement_timeout','2000', true);
  perform set_config('lock_timeout','1000', true);
  begin
    for v_rec in
      select g.id, g.base_url, g.api_path, g.software
      from public.nexus_global_anonymous_gateways g
      where g.status in ('alive','alive_tag_only') and g.api_path is not null
        -- v300: cobertura 24/7 planetária (janela 9-20h removida; caps/jitter/timeouts preservados)
        and (p_shard is null or g.cluster_shard_id = p_shard)
      order by g.last_swept_at asc nulls first, g.id asc
      limit greatest(1, least(p_max_hosts, 20))
      for update skip locked
    loop
      update public.nexus_global_anonymous_gateways set last_swept_at=now() where id=v_rec.id;
      if v_rec.software='mastodon' then
        v_url := v_rec.base_url || case when v_rec.api_path like '%/tag' then v_rec.api_path || '/oferta' else coalesce(v_rec.api_path,'/api/v1/timelines/public') end || '?limit=20';
        select net.http_get(url:=v_url, headers:=jsonb_build_object('User-Agent','NexusWave/1.0 (anonymous read-only; +https://achadinhos-ad-engine.vercel.app)'), timeout_milliseconds:=8000) into v_req;
      elsif v_rec.software='misskey' then
        v_url := v_rec.base_url || '/api/notes/local-timeline';
        select net.http_post(url:=v_url, body:='{"limit":20}'::jsonb, headers:=jsonb_build_object('Content-Type','application/json','User-Agent','NexusWave/1.0 (anonymous read-only)'), timeout_milliseconds:=8000) into v_req;
      else
        v_url := v_rec.base_url || coalesce(v_rec.api_path,'/api/v3/post/list') || '?limit=20&sort=Active';
        select net.http_get(url:=v_url, headers:=jsonb_build_object('User-Agent','NexusWave/1.0 (anonymous read-only; +https://achadinhos-ad-engine.vercel.app)'), timeout_milliseconds:=8000) into v_req;
      end if;
      insert into public.nexus_galaxy_wave_fetches (gateway_id, request_id, url) values (v_rec.id, v_req, v_url);
      v_dispatched := v_dispatched + 1;
      perform pg_sleep(random() * 0.08);
    end loop;
    v_log := 'onda v300 24/7 despachada: ' || v_dispatched || ' host(s) · shard ' || coalesce(p_shard,'TODOS (mestre)') || ' · rotação last_swept_at';
    insert into public.nexus_cron_telemetry (job,status,target_host,http_status,message)
    values ('v99_galaxy_wave','ok','fediverse',200,v_log);
    return jsonb_build_object('dispatched',v_dispatched,'shard',coalesce(p_shard,'all'),'schedule','v99-galaxy-wave-sweep-2min */2 LIVE');
  exception when others then
    insert into public.nexus_cron_telemetry (job,status,target_host,http_status,message)
    values ('v99_galaxy_wave','degraded','fediverse',0,'Sintonizado em Análise — sweep parcial (' || sqlstate || ': ' || sqlerrm || ')');
    return jsonb_build_object('dispatched',v_dispatched,'fail_closed',true,'marker','Sintonizado em Análise');
  end;
end $function$;
