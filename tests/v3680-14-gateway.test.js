#!/usr/bin/env node
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const sql = fs.readFileSync(path.join(root, "supabase/migrations/supabase_v3680_14_gateway_evidence.sql"), "utf8");
const edge = fs.readFileSync(path.join(root, "supabase/functions/nexus-target-alignment-v3680/index.ts"), "utf8");
